// `src/messages/ro.d.json.ts` is written by next-intl and checked in, and it, not `ro.json`, is what types `translate(...)`
// (engineering-conventions, rule 4). next-intl regenerates it only during `next dev` and `next build`, so a wave that edits
// the catalogue and not the declaration is told by `tsc` that a call is "missing arguments" at the call site, far from the
// cause. The declaration is a type with the catalogue's literal strings, so it is read as text and compared to the JSON.
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import { describe, expect, it } from "vitest";

import ro from "@/messages/ro.json";

import { catalogueLeaves } from "../support/catalogues";

const DECLARATION_PATH = resolve(
  import.meta.dirname,
  "../../src/messages/ro.d.json.ts",
);
const DECLARATION_HEAD = "declare const messages: ";
const DECLARATION_TAIL = ";\nexport default messages;";

function declaredMessages(): unknown {
  const source = readFileSync(DECLARATION_PATH, "utf8");
  const start = source.indexOf(DECLARATION_HEAD);
  const end = source.lastIndexOf(DECLARATION_TAIL);
  expect(start, "the declaration's head").toBeGreaterThanOrEqual(0);
  expect(end, "the declaration's tail").toBeGreaterThan(start);
  return JSON.parse(source.slice(start + DECLARATION_HEAD.length, end));
}

describe("ro.d.json.ts mirrors ro.json", () => {
  it("declares exactly the catalogue: every namespace, key and string", () => {
    expect(declaredMessages()).toEqual(ro);
  });

  it("declares the keys in the catalogue's own order, so the file is what next-intl would write", () => {
    const declared = catalogueLeaves(
      declaredMessages() as Record<string, unknown>,
    );
    expect(declared.map(([key]) => key)).toEqual(
      catalogueLeaves(ro).map(([key]) => key),
    );
  });

  it("is a type declaration with a default export and no value that could drift from the JSON", () => {
    const source = readFileSync(DECLARATION_PATH, "utf8");
    expect(
      source.startsWith("// This file is auto-generated by next-intl"),
    ).toBe(true);
    expect(source.match(/declare const /g)).toHaveLength(1);
    expect(source.match(/export default /g)).toHaveLength(1);
  });
});
